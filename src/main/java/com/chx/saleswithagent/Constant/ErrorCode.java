package com.chx.saleswithagent.Constant;

public enum ErrorCode {
    COMMON_ERROR(400,"错误");

    private final int code;
    private final String message;

    ErrorCode(int code, String message) {
        this.code = code;
        this.message = message;
    }

    public int getCode() {
        return code;
    }

    public String getMessage() {
        return message;
    }
}
